const fs=require('fs'),path=require('path'),vm=require('vm');
const root=__dirname;
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
const curriculum=fs.readFileSync(path.join(root,'curriculum-data.js'),'utf8')+'\n'+fs.readFileSync(path.join(root,'curriculum-expansion-v17-4.js'),'utf8');
const checks=[];const ok=(name,cond)=>{checks.push([name,!!cond]);if(!cond)process.exitCode=1};
const sandbox={window:{}};vm.createContext(sandbox);vm.runInContext(curriculum,sandbox);
const C=sandbox.window.ISC_CURRICULUM||{};
const expected=['khmer','english','mandarin','spanish','french','japanese','arabic'];
ok('All seven language courses exist',expected.every(k=>C.languages?.[k]));
ok('Every language has 150 guided units',expected.every(k=>C.languages[k].units?.length===150));
ok('Every lesson uses the shared 8-block progression',Array.isArray(C.sessionTypes)&&C.sessionTypes.length===8);
ok('Curriculum declares 1200 blocks per language',C.activityCountPerLanguage===1200);
const ids=[];for(const lang of expected)for(let u=1;u<=150;u++)for(let s=1;s<=8;s++)ids.push(`${lang}-u${u}-d1-s${s}`);
ok('All 8,400 language block IDs are unique',ids.length===8400&&new Set(ids).size===8400);
ok('Completion saves study progress',app.includes('state.studyCompleted.push(id)')&&app.includes("save();"));
ok('Blocks 1-7 return to current block list',app.includes('openStudyDay(unitIndex,dayIndex);')&&!app.includes('if(!lastBlock){openStudySession(unitIndex,dayIndex,sessionIndex+1);return}'));
ok('Block 8 also returns to current block list after marking complete',app.includes('openStudyDay(unitIndex,dayIndex);')&&!app.includes('if(!lastUnit){openStudyDay(unitIndex+1,0);return}'));
ok('Next lesson unlock still requires prior 8 blocks',app.includes(".length>=8")&&app.includes('previousDone'));
ok('Completion persistence is synced to account API',server.includes("'studyCompleted'")&&server.includes("'/api/account/progress'"));
ok('Final course completion still awards certificate',app.includes('if(!wasComplete&&courseComplete(lang)){maybeAwardCertificate(lang);return}'));
ok('Mastery pass uses same completion handler',app.includes('if(pass)completeStudy(unitIndex,dayIndex,sessionIndex)'));
for(const [n,v] of checks)console.log(`${v?'PASS':'FAIL'} ${n}`);
const passed=checks.filter(x=>x[1]).length;console.log(`\nV18.8.15 progression QA: ${passed}/${checks.length} passed`);if(passed!==checks.length)process.exitCode=1;
